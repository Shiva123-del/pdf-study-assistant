import json
import os
import sys

from dotenv import load_dotenv
from openai import OpenAI

# Allow importing app.py from the project root
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BASE_DIR)

from app import search, get_vector_store


load_dotenv()

client = OpenAI()

GENERATOR_MODEL = "gpt-4.1-mini"
JUDGE_MODEL = "gpt-5.6-sol"

DATASET_PATH = os.path.join(
    BASE_DIR,
    "evaluation",
    "test_dataset.json"
)

OUTPUT_PATH = os.path.join(
    BASE_DIR,
    "evaluation",
    "answer_evaluation_independent_results.json"
)

TOP_K = 5


def load_dataset():
    with open(DATASET_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def get_document_id():
    """
    Get the first document stored in Chroma.
    """
    vector_store = get_vector_store()

    data = vector_store.get(
        include=["metadatas"]
    )

    metadatas = data.get("metadatas", [])

    if not metadatas:
        raise RuntimeError(
            "No documents found in the Chroma database."
        )

    document_ids = [
        metadata.get("document_id")
        for metadata in metadatas
        if metadata.get("document_id")
    ]

    if not document_ids:
        raise RuntimeError(
            "No document_id found in the Chroma database."
        )

    return document_ids[0]


def build_context(results):
    """
    Convert retrieved chunks into a readable context block.
    """
    context_parts = []

    for i, doc in enumerate(results, start=1):
        metadata = doc.metadata

        source = metadata.get("source", "Unknown")
        page = metadata.get("page_number", "?")

        context_parts.append(
            f"[Context {i}] "
            f"Source: {source}, Page: {page}\n"
            f"{doc.page_content}"
        )

    return "\n\n".join(context_parts)


def generate_answer(question, document_id):
    """
    Generate an answer using the same RAG pipeline
    used by the application.
    """
    results = search(
        question,
        document_id=document_id,
        k=TOP_K
    )

    context = build_context(results)

    prompt = f"""
You are answering a question using a retrieval-augmented
generation system.

Use ONLY the information contained in the context below.

If the context does not contain enough information to answer
the question, explicitly say that the information is not
available in the provided context.

Question:
{question}

Context:
{context}

Give a concise, accurate answer.
Include source references in the form:
(Source: filename, p. X)
"""

    response = client.responses.create(
        model=GENERATOR_MODEL,
        input=prompt
    )

    answer = response.output_text

    return answer, context


def judge_answer(question, answer, context):
    """
    Use an independent, stronger model to evaluate the answer.
    """

    judge_prompt = f"""
You are an independent evaluator assessing a RAG system.

The answer was generated by another model.

Do NOT assume the answer is correct.
Evaluate it strictly against the provided context.

Question:
{question}

Retrieved Context:
{context}

Generated Answer:
{answer}

Evaluate the answer on three dimensions.

1. Faithfulness
Does every factual claim in the answer have support in
the retrieved context?

2. Answer Relevancy
Does the answer directly and appropriately answer the
question without unnecessary information?

3. Correctness
Is the answer factually correct according to the
retrieved context?

Use a score from 1 to 5:

1 = Very poor
2 = Poor
3 = Partially correct
4 = Good
5 = Excellent

Return ONLY valid JSON in exactly this format:

{{
    "faithfulness": {{
        "score": 1,
        "reason": "short explanation"
    }},
    "answer_relevancy": {{
        "score": 1,
        "reason": "short explanation"
    }},
    "correctness": {{
        "score": 1,
        "reason": "short explanation"
    }}
}}
"""

    response = client.responses.create(
        model=JUDGE_MODEL,
        input=judge_prompt
    )

    raw = response.output_text.strip()

    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        print("\nWARNING: Judge returned invalid JSON:")
        print(raw)

        return {
            "faithfulness": {
                "score": None,
                "reason": "Invalid judge response"
            },
            "answer_relevancy": {
                "score": None,
                "reason": "Invalid judge response"
            },
            "correctness": {
                "score": None,
                "reason": "Invalid judge response"
            }
        }


def main():

    print("=" * 70)
    print("INDEPENDENT RAG ANSWER EVALUATION")
    print("=" * 70)

    dataset = load_dataset()

    print(f"\nQuestions: {len(dataset)}")
    print(f"Generator: {GENERATOR_MODEL}")
    print(f"Independent Judge: {JUDGE_MODEL}")
    print(f"Top-K retrieval: {TOP_K}")

    document_id = get_document_id()

    print("\nDocument ID found.")
    print("Starting evaluation...\n")

    results = []

    for index, item in enumerate(dataset, start=1):

        question_id = item["id"]
        question = item["question"]

        print(
            f"[{index}/{len(dataset)}] "
            f"Evaluating {question_id}: {question}"
        )

        try:
            answer, context = generate_answer(
                question,
                document_id
            )

            evaluation = judge_answer(
                question,
                answer,
                context
            )

            result = {
                "id": question_id,
                "question": question,
                "answer": answer,
                "evaluation": evaluation
            }

            results.append(result)

            print(
                f"  Faithfulness: "
                f"{evaluation['faithfulness']['score']}/5"
            )

            print(
                f"  Relevancy: "
                f"{evaluation['answer_relevancy']['score']}/5"
            )

            print(
                f"  Correctness: "
                f"{evaluation['correctness']['score']}/5"
            )

        except Exception as e:

            print(f"  ERROR: {e}")

            results.append({
                "id": question_id,
                "question": question,
                "error": str(e)
            })

    with open(
        OUTPUT_PATH,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            results,
            f,
            indent=2,
            ensure_ascii=False
        )

    # Calculate averages
    faithfulness_scores = []
    relevancy_scores = []
    correctness_scores = []

    for result in results:

        evaluation = result.get("evaluation")

        if not evaluation:
            continue

        f_score = evaluation["faithfulness"]["score"]
        r_score = evaluation["answer_relevancy"]["score"]
        c_score = evaluation["correctness"]["score"]

        if isinstance(f_score, (int, float)):
            faithfulness_scores.append(f_score)

        if isinstance(r_score, (int, float)):
            relevancy_scores.append(r_score)

        if isinstance(c_score, (int, float)):
            correctness_scores.append(c_score)

    print("\n" + "=" * 70)
    print("FINAL RESULTS")
    print("=" * 70)

    if faithfulness_scores:
        print(
            f"Faithfulness: "
            f"{sum(faithfulness_scores) / len(faithfulness_scores):.2f}/5"
        )

    if relevancy_scores:
        print(
            f"Answer Relevancy: "
            f"{sum(relevancy_scores) / len(relevancy_scores):.2f}/5"
        )

    if correctness_scores:
        print(
            f"Correctness: "
            f"{sum(correctness_scores) / len(correctness_scores):.2f}/5"
        )

    print(f"\nDetailed results saved to:")
    print(OUTPUT_PATH)


if __name__ == "__main__":
    main()